const OPEN_INVOICE = ['SENT', 'UNPAID', 'PAYMENT_PENDING', 'PARTIALLY_PAID', 'SCHEDULED']; // still waiting for money
const SETTLED_PAYOUT = ['SUCCESS', 'DENIED', 'FAILED', 'RETURNED', 'REFUNDED', 'CANCELED', 'BLOCKED', 'UNCLAIMED'];
const cleanNote = (n) => String(n || '').replace(/[\u0000-\u001f<>]/g, ' ').trim().slice(0, 100);
const paypalLinkOk = (u) => typeof u === 'string' && /^https:\/\/(www\.)?(sandbox\.)?paypal\.com\//.test(u);

async function createAndSendInvoice(payee, value, note) {
  const token = await getAccessToken();
  const headers = { 'Content-Type': 'application/json', Authorization: `Bearer ${token}` };
  const amountStr = value.toFixed(2);

  let number;
  try {
    number = (await axios.post(`${PAYPAL_API_BASE}/v2/invoicing/generate-next-invoice-number`, {}, { headers, timeout: 10000 })).data?.invoice_number;
  } catch (_) { /* PayPal will assign one */ }

  const created = await axios.post(
    `${PAYPAL_API_BASE}/v2/invoicing/invoices`,
    {
      detail: {
        currency_code: 'USD',
        ...(number ? { invoice_number: number } : {}),
        note: cleanNote(note) || 'Requested with InclusivePay',
        payment_term: { term_type: 'DUE_ON_RECEIPT' },
      },
      primary_recipients: [{ billing_info: { name: { given_name: payee.name }, email_address: payee.email } }],
      items: [{ name: 'InclusivePay request', quantity: '1', unit_amount: { currency_code: 'USD', value: amountStr } }],
    },
    { headers, timeout: 15000 }
  );
  const id = created.data?.id || String(created.data?.href || '').split('/').pop();
  if (!id) throw new Error('PayPal did not return an invoice id');

  try {
    await axios.post(`${PAYPAL_API_BASE}/v2/invoicing/invoices/${encodeURIComponent(id)}/send`, { send_to_recipient: true, send_to_invoicer: false }, { headers, timeout: 15000 });
  } catch (err) {
    // Don't leave an unsent draft behind
    axios.delete(`${PAYPAL_API_BASE}/v2/invoicing/invoices/${encodeURIComponent(id)}`, { headers, timeout: 8000 }).catch(() => {});
    throw err;
  }

  let detail = {};
  try {
    detail = (await axios.get(`${PAYPAL_API_BASE}/v2/invoicing/invoices/${encodeURIComponent(id)}`, { headers, timeout: 10000 })).data || {};
  } catch (_) { /* fine: status defaults to SENT */ }
  const link = detail.detail?.metadata?.recipient_view_url;

  const record = {
    id,
    number: detail.detail?.invoice_number || number || '',
    recipient: payee.name,
    email: payee.email,
    amount: `$${amountStr}`,
    status: detail.status || 'SENT',
    note: cleanNote(note),
    link: paypalLinkOk(link) ? link : '',
    date: new Date().toLocaleDateString() + ' ' + new Date().toLocaleTimeString(),
    ts: Date.now(),
  };
  invoiceHistory.unshift(record);
  saveInvoices();
  addFeed(`Invoice for ${record.amount} sent to ${payee.name} (${record.status}).`, 'app');
  return record;
}

