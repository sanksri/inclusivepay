async function getAccessToken() {
  const auth = Buffer.from(`${PAYPAL_CLIENT_ID}:${PAYPAL_SECRET}`).toString('base64');
  const response = await axios({
    url: `${PAYPAL_API_BASE}/v1/oauth2/token`,
    method: 'post',
    timeout: 10000,
    headers: { 'Content-Type': 'application/x-www-form-urlencoded', Authorization: `Basic ${auth}` },
    data: 'grant_type=client_credentials',
  });
  return response.data.access_token;
}

// The one place money moves. Used by /send-money and /agent/confirm.
async function executePayment(payee, value) {
  const token = await getAccessToken();
  const batchId = 'batch-' + Date.now() + '-' + crypto.randomBytes(3).toString('hex');
  const amountStr = value.toFixed(2);

  const response = await axios({
    url: `${PAYPAL_API_BASE}/v1/payments/payouts`,
    method: 'post',
    timeout: 15000,
    headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${token}` },
    data: {
      sender_batch_header: { sender_batch_id: batchId, email_subject: 'You have a payment from InclusivePay' },
      items: [
        {
          recipient_type: 'EMAIL',
          amount: { value: amountStr, currency: 'USD' },
          receiver: payee.email,
          note: 'InclusivePay voice-assisted payment',
        },
      ],
    },
  });

  const header = response.data.batch_header || {};
  const txRecord = {
    id: header.payout_batch_id || batchId,
    recipient: payee.name,
    email: payee.email,
    amount: `$${amountStr}`,
    status: header.batch_status || 'PENDING', // PayPal's own status, refreshed on /transactions
    date: new Date().toLocaleDateString() + ' ' + new Date().toLocaleTimeString(),
    ts: Date.now(),
  };
  transactionHistory.unshift(txRecord);
  saveTransactions();
  addFeed(`Payment of $${amountStr} to ${payee.name} created (${txRecord.status}).`, 'app');
  return txRecord;
}

