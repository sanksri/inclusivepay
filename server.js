// Abuse protection: PIN lockout and request limits (per IP)
// ---------------------------------------------------------------------------
const pinFailures = new Map(); // ip -> { count, lockedUntil }
function pinLocked(ip) {
  const rec = pinFailures.get(ip);
  return rec && rec.lockedUntil > Date.now() ? Math.ceil((rec.lockedUntil - Date.now()) / 1000) : 0;
}
function pinFailed(ip) {
  const rec = pinFailures.get(ip) || { count: 0, lockedUntil: 0 };
  rec.count += 1;
  if (rec.count >= 5) { rec.lockedUntil = Date.now() + 60000; rec.count = 0; }
  pinFailures.set(ip, rec);
}
// Returns an error response object if the PIN can't be accepted, else null.
function checkPin(req, pin) {
  const wait = pinLocked(req.ip);
  if (wait) return { status: 429, error: `Too many wrong PINs. Try again in ${wait} seconds.` };
  if (typeof pin !== 'string' || pin !== APP_PIN) {
    pinFailed(req.ip);
    return { status: 401, error: 'Authentication failed: invalid or missing PIN.' };
  }
  return null;
}

function makeLimiter(limit, windowMs = 60000) {
  const hitsByIp = new Map(); // ip -> [timestamps]
  return (ip) => {
    const now = Date.now();
    const hits = (hitsByIp.get(ip) || []).filter((t) => now - t < windowMs);
    hits.push(now);
    hitsByIp.set(ip, hits);
    if (hitsByIp.size > 2000) hitsByIp.clear();
    return hits.length > limit;
  };
}
