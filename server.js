const sseClients = new Set();
function broadcast(payload) {
  const msg = `event: update\ndata: ${JSON.stringify(payload)}\n\n`;
  for (const res of sseClients) { try { res.write(msg); } catch (_) { sseClients.delete(res); } }
}
const feed = []; // newest first, kept in memory only
// source: 'app' (we did it), 'webhook' (PayPal told us), 'poll' (we asked PayPal), 'simulated' (demo button)
function addFeed(text, source) {
  const item = { id: crypto.randomBytes(4).toString('hex'), text, source, at: new Date().toISOString() };
  feed.unshift(item);
  if (feed.length > 50) feed.length = 50;
  broadcast({ kind: 'feed', item });
  return item;
}

