async function getBalance() {
  try {
    const { result } = await paypalClient.transactionSearchController.searchBalances({ currencyCode: 'USD' });
    const bal = result?.balances?.find((b) => b.primary) || result?.balances?.[0];
    const value = bal?.totalBalance?.value;
    if (value !== undefined) return { balance: `$${Number(value).toFixed(2)}`, source: 'paypal' };
    throw new Error('No balance in response');
  } catch (err) {
    const spent = transactionHistory.reduce((sum, t) => sum + (parseFloat(String(t.amount).replace('$', '')) || 0), 0);
    return { balance: `$${Math.max(0, STARTING_BALANCE - spent).toFixed(2)}`, source: 'sandbox-mock' };
  }
}

