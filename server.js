// ---------------------------------------------------------------------------
// Payment proposals (created by the AI agent, executed only after confirm + PIN)
// ---------------------------------------------------------------------------
const PROPOSAL_TTL_MS = 5 * 60 * 1000;
const proposals = new Map(); // id -> { id, type, payee, value, note, label, ip, createdAt, used }
function newProposal(ip, payee, value, type = 'payment', note = '') {
  const now = Date.now();
  for (const [id, p] of proposals) if (now - p.createdAt > PROPOSAL_TTL_MS) proposals.delete(id);
  if (proposals.size > 500) proposals.clear();
  const id = crypto.randomBytes(6).toString('hex');
  const label = type === 'invoice' ? `Request from ${payee.name}` : payee.kind === 'bill' ? `Pay ${payee.name}` : `Send to ${payee.name}`;
  const p = { id, type, payee, value, note, label, ip, createdAt: now, used: false };
  proposals.set(id, p);
  return p;
}

