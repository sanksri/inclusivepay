// PayPal webhook receiver. Every delivery is verified with PayPal before we believe it.
app.post('/webhooks/paypal', express.json({ limit: '200kb' }), async (req, res) => {
  if (!WEBHOOK_ID) return res.status(503).json({ error: 'Webhooks are not configured (set PAYPAL_WEBHOOK_ID).' });
  const event = req.body;
  if (!event || typeof event !== 'object' || !event.id || !event.event_type) return res.status(400).json({ error: 'Not a PayPal event.' });
  const h = req.headers;
  try {
    const token = await getAccessToken();
    const v = await axios.post(
      `${PAYPAL_API_BASE}/v1/notifications/verify-webhook-signature`,
      {
        auth_algo: h['paypal-auth-algo'],
        cert_url: h['paypal-cert-url'],
        transmission_id: h['paypal-transmission-id'],
        transmission_sig: h['paypal-transmission-sig'],
        transmission_time: h['paypal-transmission-time'],
        webhook_id: WEBHOOK_ID,
        webhook_event: event,
      },
      { headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${token}` }, timeout: 10000 }
    );
    if (v.data?.verification_status !== 'SUCCESS') return res.status(400).json({ error: 'Signature verification failed.' });
  } catch (err) {
    console.error('Webhook verification error:', err.response ? JSON.stringify(err.response.data).slice(0, 200) : err.message);
    return res.status(err.response?.status === 400 ? 400 : 502).json({ error: 'Could not verify the webhook.' }); // non-400: PayPal retries
  }
  if (seenEvents.has(event.id)) return res.json({ ok: true, duplicate: true });
  seenEvents.add(event.id);
  if (seenEvents.size > 1000) seenEvents.delete(seenEvents.values().next().value);
  const out = applyEvent(event, 'webhook');
  console.log(`Webhook ${event.event_type}: ${out.handled ? 'applied' : out.reason}`);
  res.json({ ok: true, handled: out.handled });
});
