const titleCase = (s) => s.charAt(0).toUpperCase() + s.slice(1);

// Turns free text into a known payee. Arbitrary text is never stored or emailed.
function resolvePayee(text) {
  const words = String(text).toLowerCase().replace(/[^a-z0-9 ]/g, ' ').split(/\s+/).filter(Boolean);
  const billKey = Object.keys(PENDING_BILLS).find((b) => words.includes(b));
  const contactKey = Object.keys(CONTACTS).find((c) => words.includes(c));
  if (billKey) {
    return { kind: 'bill', key: billKey, name: `${titleCase(billKey)} Bill`, email: BILLER_EMAILS[billKey] || `${billKey}-bill@billers.example.com`, due: PENDING_BILLS[billKey] };
  }
  if (contactKey) return { kind: 'person', key: contactKey, name: titleCase(contactKey), email: CONTACTS[contactKey] };
  if (words.includes('bill') || words.includes('utility')) {
    return { error: 'Which bill? Say electricity, internet, water, gas or phone.' };
  }
  return { error: `I don't have "${String(text).trim().slice(0, 30)}" in your contacts.` };
}

function validateAmount(amount) {
  const value = Number(amount);
  if (amount === undefined || amount === null || amount === '' || !Number.isFinite(value) || value <= 0) {
    return { error: 'Amount must be a number greater than zero.' };
  }
  if (value > MAX_AMOUNT) return { error: `Amount is above the $${MAX_AMOUNT} demo limit.` };
  return { value: Math.round(value * 100) / 100 };
}

