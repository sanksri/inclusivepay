// Transactions for AG Grid. Refreshes the status of payouts PayPal hasn't finalized yet.
app.get('/transactions', async (req, res) => {
  const unsettled = transactionHistory
    .filter((t) => ['PENDING', 'PROCESSING'].includes(t.status) && !String(t.id).startsWith('batch-'))
    .slice(0, 5);
  if (unsettled.length) {
    try {
      const token = await getAccessToken();
      await Promise.all(
        unsettled.map(async (t) => {
          try {
            const r = await axios.get(`${PAYPAL_API_BASE}/v1/payments/payouts/${encodeURIComponent(t.id)}`, {
              headers: { Authorization: `Bearer ${token}` },
              timeout: 8000,
            });
            const itemStatus = String(r.data?.items?.[0]?.transaction_status || '').toUpperCase();
            const status = ITEM_PROBLEMS.includes(itemStatus) ? itemStatus : r.data?.batch_header?.batch_status; // the item's problem wins over the batch
            if (status && status !== t.status) { t.status = status; addFeed(`Payment of ${t.amount} to ${t.recipient} is now ${status}.${statusNote(status)}`, 'poll'); }
          } catch (_) { /* keep old status */ }
        })
      );
      saveTransactions();
    } catch (_) { /* PayPal unreachable: return what we have */ }
  }
  res.json({ transactions: transactionHistory });
});

