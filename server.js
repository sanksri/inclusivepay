// Ask PayPal about invoices that are still waiting for money (fallback when webhooks are off).
async function refreshInvoices() {
  const open = invoiceHistory.filter((i) => OPEN_INVOICE.includes(i.status)).slice(0, 5);
  if (!open.length) return;
  try {
    const token = await getAccessToken();
    let changed = false;
    await Promise.all(open.map(async (i) => {
      try {
        const r = await axios.get(`${PAYPAL_API_BASE}/v2/invoicing/invoices/${encodeURIComponent(i.id)}`, { headers: { Authorization: `Bearer ${token}` }, timeout: 8000 });
        const status = r.data?.status;
        if (status && status !== i.status) { i.status = status; changed = true; addFeed(`Invoice to ${i.recipient} (${i.amount}) is now ${status}.`, 'poll'); }
      } catch (_) { /* keep old status */ }
    }));
    if (changed) saveInvoices();
  } catch (_) { /* PayPal unreachable */ }
}

